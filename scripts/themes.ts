type Json = Record<string, unknown>;

const HEX = /^#[0-9A-Fa-f]{6}$/;
const REFERENCE = /^\{([^{}]+)\}$/;

const isObject = (value: unknown): value is Json =>
  typeof value === "object" && value !== null && !Array.isArray(value);

function collect(node: Json, path: string[], out: Map<string, string>) {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$") || !isObject(child)) continue;
    const childPath = [...path, key];
    if (typeof child.$value === "string") {
      out.set(childPath.join("."), child.$value);
    } else {
      collect(child, childPath, out);
    }
  }
}

function cssName(path: string): string {
  const [first, ...rest] = path.split(".");
  return first === "semantic"
    ? `color-${rest.join("-")}`
    : `color-${path.split(".").join("-")}`;
}

function displayP3(hex: string): string {
  const channels = [1, 3, 5].map((i) =>
    Number((parseInt(hex.slice(i, i + 2), 16) / 255).toFixed(4)),
  );
  return `color(display-p3 ${channels.join(" ")})`;
}

function leaves(tree: Json): Map<string, string> {
  const out = new Map<string, string>();
  collect(tree, [], out);
  return out;
}

export function resolveHex(tree: Json, path: string): string {
  const all = leaves(tree);
  let value = all.get(path);
  for (let hops = 0; value !== undefined && hops < 10; hops++) {
    const ref = REFERENCE.exec(value);
    if (!ref) return value;
    value = all.get(ref[1]!);
  }
  throw new Error(`${path}: does not resolve to a hex`);
}

// Every theme must define exactly the base semantic names, so a product
// page never renders with a missing or unknown role.
export function themeCss(name: string, tree: Json, roles: string[]): string {
  const all = leaves(tree);
  const declarations: string[] = [];

  for (const [path, value] of all) {
    const ref = REFERENCE.exec(value);
    if (ref) {
      if (!all.has(ref[1]!)) {
        throw new Error(`${path}: "${value}" does not resolve`);
      }
      declarations.push(`  --${cssName(path)}: var(--${cssName(ref[1]!)});`);
    } else if (HEX.test(value)) {
      declarations.push(`  --${cssName(path)}: ${displayP3(value)};`);
    } else {
      throw new Error(
        `${path}: "${value}" is not a #RRGGBB hex or a reference`,
      );
    }
  }

  const defined = [...all.keys()]
    .filter((path) => path.startsWith("semantic."))
    .map((path) => path.slice("semantic.".length));
  for (const role of roles) {
    if (!defined.includes(role)) {
      throw new Error(`Theme "${name}" is missing semantic token "${role}"`);
    }
  }
  for (const role of defined) {
    if (!roles.includes(role)) {
      throw new Error(
        `Theme "${name}" defines "${role}", which is not a semantic token`,
      );
    }
  }

  return [
    "/* Generated by scripts/build.ts. Do not edit. */",
    `[data-theme="${name}"] {`,
    ...declarations,
    "}",
    "",
  ].join("\n");
}
