import { mkdir } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import StyleDictionary from "style-dictionary";
import { formattedVariables } from "style-dictionary/utils";
import { toCssColor, type ColorValue } from "./color.ts";
import { toModule } from "./emit-module.ts";
import { copyFonts, fontManifest, fontsCss } from "./fonts.ts";
import { cssName } from "./names.ts";
import { validateExport } from "./validate-export.ts";

const REPO_ROOT = fileURLToPath(new URL("..", import.meta.url));

StyleDictionary.registerTransform({
  name: "omnypotent/color",
  type: "value",
  filter: (token) =>
    token.$type === "color" && typeof token.$value === "object",
  transform: (token) => toCssColor(token.$value as ColorValue),
});

StyleDictionary.registerTransform({
  name: "omnypotent/name",
  type: "name",
  transform: (token) => cssName(token.path),
});

StyleDictionary.registerFormat({
  name: "omnypotent/css",
  format: ({ dictionary, options }) => {
    const variables = formattedVariables({
      format: "css",
      dictionary,
      outputReferences: options.outputReferences,
      usesDtcg: true,
    });
    return [
      "/* Generated by scripts/build.ts. Do not edit. */",
      ":root {",
      "  color-scheme: dark;",
      variables,
      "}",
      "",
    ].join("\n");
  },
});

type Tokens = {
  color: Record<string, string>;
  font: { family: Record<string, string>; size: Record<string, string> };
};

const TOKEN_GROUPS: [
  prefix: string,
  place: (t: Tokens) => Record<string, string>,
][] = [
  ["color-", (t) => t.color],
  ["font-family-", (t) => t.font.family],
  ["font-size-", (t) => t.font.size],
];

StyleDictionary.registerFormat({
  name: "omnypotent/tokens-json",
  format: ({ dictionary }) => {
    const tokens: Tokens = { color: {}, font: { family: {}, size: {} } };
    for (const token of dictionary.allTokens) {
      const group = TOKEN_GROUPS.find(([prefix]) =>
        token.name.startsWith(prefix),
      );
      if (!group) throw new Error(`No place in tokens.json for ${token.name}`);
      const [prefix, place] = group;
      place(tokens)[token.name.slice(prefix.length)] = String(token.$value);
    }
    return `${JSON.stringify(tokens, null, 2)}\n`;
  },
});

export type BuildOptions = { root?: string; outDir?: string };

export async function build(options: BuildOptions = {}): Promise<void> {
  const root = options.root ?? REPO_ROOT;
  const outDir = options.outDir ?? join(root, "dist");

  const issues = validateExport(
    await Bun.file(join(root, "tokens/figma/variables.json")).json(),
  );
  if (issues.length > 0) {
    const lines = issues.map((i) => `${i.path}: ${i.message}`);
    throw new Error(`Invalid Figma export:\n${lines.join("\n")}`);
  }

  await mkdir(outDir, { recursive: true });
  const dictionary = new StyleDictionary({
    usesDtcg: true,
    log: { verbosity: "verbose" },
    source: [
      join(root, "tokens/figma/variables.json"),
      join(root, "tokens/semantic/*.json"),
      join(root, "tokens/type/*.json"),
    ],
    platforms: {
      css: {
        transforms: ["omnypotent/color", "omnypotent/name"],
        buildPath: `${outDir}/`,
        files: [
          {
            destination: "tokens.css",
            format: "omnypotent/css",
            options: { outputReferences: true },
          },
          { destination: "tokens.json", format: "omnypotent/tokens-json" },
        ],
      },
    },
  });
  await dictionary.buildAllPlatforms();

  const tokens = await Bun.file(join(outDir, "tokens.json")).json();
  await copyFonts(outDir);
  const manifest = fontManifest();
  await Bun.write(join(outDir, "fonts.css"), fontsCss(manifest));
  await Bun.write(
    join(outDir, "fonts.json"),
    `${JSON.stringify(manifest, null, 2)}\n`,
  );

  const modules = [toModule("tokens", tokens), toModule("fonts", manifest)];
  await Bun.write(join(outDir, "index.js"), modules.map((m) => m.js).join(""));
  await Bun.write(
    join(outDir, "index.d.ts"),
    modules.map((m) => m.dts).join(""),
  );
}

if (import.meta.main) {
  await build({ outDir: process.env.OUT_DIR });
}
