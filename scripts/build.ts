import { mkdir } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import StyleDictionary from "style-dictionary";
import { formattedVariables } from "style-dictionary/utils";
import { toCssColor, type ColorValue } from "./color.ts";
import { cssName } from "./names.ts";
import { validateExport } from "./validate-export.ts";

const REPO_ROOT = fileURLToPath(new URL("..", import.meta.url));

StyleDictionary.registerTransform({
  name: "omnypotent/color",
  type: "value",
  filter: (token) =>
    token.$type === "color" && typeof token.$value === "object",
  transform: (token) => toCssColor(token.$value as ColorValue),
});

StyleDictionary.registerTransform({
  name: "omnypotent/name",
  type: "name",
  transform: (token) => cssName(token.path),
});

StyleDictionary.registerFormat({
  name: "omnypotent/css",
  format: ({ dictionary, options }) => {
    const variables = formattedVariables({
      format: "css",
      dictionary,
      outputReferences: options.outputReferences,
      usesDtcg: true,
    });
    return [
      "/* Generated by scripts/build.ts. Do not edit. */",
      ":root {",
      "  color-scheme: dark;",
      variables,
      "}",
      "",
    ].join("\n");
  },
});

export type BuildOptions = { root?: string; outDir?: string };

export async function build(options: BuildOptions = {}): Promise<void> {
  const root = options.root ?? REPO_ROOT;
  const outDir = options.outDir ?? join(root, "dist");

  const issues = validateExport(
    await Bun.file(join(root, "tokens/figma/variables.json")).json(),
  );
  if (issues.length > 0) {
    const lines = issues.map((i) => `${i.path}: ${i.message}`);
    throw new Error(`Invalid Figma export:\n${lines.join("\n")}`);
  }

  await mkdir(outDir, { recursive: true });
  const dictionary = new StyleDictionary({
    usesDtcg: true,
    log: { verbosity: "verbose" },
    source: [
      join(root, "tokens/figma/variables.json"),
      join(root, "tokens/semantic/*.json"),
      join(root, "tokens/type/*.json"),
    ],
    platforms: {
      css: {
        transforms: ["omnypotent/color", "omnypotent/name"],
        buildPath: `${outDir}/`,
        files: [
          {
            destination: "tokens.css",
            format: "omnypotent/css",
            options: { outputReferences: true },
          },
        ],
      },
    },
  });
  await dictionary.buildAllPlatforms();
}

if (import.meta.main) {
  await build({ outDir: process.env.OUT_DIR });
}
