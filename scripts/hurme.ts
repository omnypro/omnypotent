const CDN = "https://cdn.omnyist.productions/hurme";
const FAMILY = "Hurme Geometric Sans 2";

const WEIGHTS = [
  ["Hairline", 100],
  ["Thin", 200],
  ["Light", 300],
  ["Regular", 400],
  ["SemiBold", 600],
  ["Bold", 700],
  ["Black", 900],
] as const;

const SLANTS = [
  ["", "normal"],
  ["Oblique", "oblique"],
] as const;

// The files are licensed, so the package carries URLs and never the fonts.
export function hurmeCss(): string {
  const blocks = SLANTS.flatMap(([suffix, style]) =>
    WEIGHTS.map(([name, weight]) => {
      const base = `${CDN}/HurmeGeometricSans2-${name}${suffix}`;
      return [
        "@font-face {",
        `  font-family: "${FAMILY}";`,
        `  font-style: ${style};`,
        "  font-display: swap;",
        `  font-weight: ${weight};`,
        `  src: url("${base}.woff2") format("woff2"),`,
        `    url("${base}.woff") format("woff");`,
        "}",
      ].join("\n");
    }),
  );
  return `/* Generated by scripts/build.ts. Do not edit. */\n${blocks.join("\n\n")}\n`;
}
