import { copyFile, mkdir } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = fileURLToPath(new URL("..", import.meta.url));

export type FontFile = {
  family: string;
  weight: string;
  style: "normal";
  subset: Subset;
  unicodeRange: string;
  format: "woff2" | "woff";
  path: string;
  url: null;
};

const SUBSETS = {
  latin:
    "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD",
  "latin-ext":
    "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF",
  vietnamese:
    "U+0102-0103,U+0110-0111,U+0128-0129,U+0168-0169,U+01A0-01A1,U+01AF-01B0,U+0300-0301,U+0303-0304,U+0308-0309,U+0323,U+0329,U+1EA0-1EF9,U+20AB",
} as const;

type Subset = keyof typeof SUBSETS;

// Later faces win where ranges overlap, so latin comes last.
const CSS_ORDER: Subset[] = ["vietnamese", "latin-ext", "latin"];

type Source = {
  pkg: string;
  family: string;
  weight: string;
  basename: (subset: Subset) => string;
  formats: FontFile["format"][];
};

const SOURCES: Source[] = [
  {
    pkg: "@fontsource-variable/space-grotesk",
    family: "Space Grotesk Variable",
    weight: "300 700",
    basename: (subset) => `space-grotesk-${subset}-wght-normal`,
    formats: ["woff2"],
  },
  {
    pkg: "@fontsource/space-mono",
    family: "Space Mono",
    weight: "400",
    basename: (subset) => `space-mono-${subset}-400-normal`,
    formats: ["woff2", "woff"],
  },
  {
    pkg: "@fontsource/space-mono",
    family: "Space Mono",
    weight: "700",
    basename: (subset) => `space-mono-${subset}-700-normal`,
    formats: ["woff2", "woff"],
  },
];

const LICENSES = [
  {
    pkg: "@fontsource-variable/space-grotesk",
    name: "LICENSE-space-grotesk.txt",
  },
  { pkg: "@fontsource/space-mono", name: "LICENSE-space-mono.txt" },
];

const subsets = Object.keys(SUBSETS) as Subset[];

export function fontManifest(): FontFile[] {
  return SOURCES.flatMap((source) =>
    subsets.flatMap((subset) =>
      source.formats.map((format) => ({
        family: source.family,
        weight: source.weight,
        style: "normal" as const,
        subset,
        unicodeRange: SUBSETS[subset],
        format,
        path: `fonts/${source.basename(subset)}.${format}`,
        url: null,
      })),
    ),
  );
}

export function fontsCss(manifest: FontFile[]): string {
  const faces = new Map<string, FontFile[]>();
  for (const font of manifest) {
    const key = `${font.family}|${font.weight}|${font.subset}`;
    faces.set(key, [...(faces.get(key) ?? []), font]);
  }
  const groups = [...new Set(manifest.map((f) => `${f.family}|${f.weight}`))];
  const blocks = groups.flatMap((group) =>
    CSS_ORDER.flatMap((subset) => {
      const files = faces.get(`${group}|${subset}`);
      if (!files) return [];
      const [first] = files;
      const sources = files
        .map((f) => `url("./${f.path}") format("${f.format}")`)
        .join(",\n    ");
      return [
        [
          "@font-face {",
          `  font-family: "${first!.family}";`,
          `  font-style: ${first!.style};`,
          "  font-display: swap;",
          `  font-weight: ${first!.weight};`,
          `  src: ${sources};`,
          `  unicode-range: ${first!.unicodeRange};`,
          "}",
        ].join("\n"),
      ];
    }),
  );
  return `/* Generated by scripts/build.ts. Do not edit. */\n${blocks.join("\n\n")}\n`;
}

export async function copyFonts(outDir: string): Promise<void> {
  const modules = join(REPO_ROOT, "node_modules");
  await mkdir(join(outDir, "fonts"), { recursive: true });
  for (const source of SOURCES) {
    for (const subset of subsets) {
      for (const format of source.formats) {
        const file = `${source.basename(subset)}.${format}`;
        await copyFile(
          join(modules, source.pkg, "files", file),
          join(outDir, "fonts", file),
        );
      }
    }
  }
  for (const license of LICENSES) {
    await copyFile(
      join(modules, license.pkg, "LICENSE"),
      join(outDir, "fonts", license.name),
    );
  }
}
